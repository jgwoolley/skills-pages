// Installable web app: the manifest, an offline-capable service worker and favicon.ico.
//
// The service worker only touches same-site GET requests under the site's own path (so sibling Pages sites on one
// origin don't share or delete each other's caches). Pages and JSON are network-first (always fresh online, cached
// copy offline); versioned assets are cache-first; zips and the well-known index always come from the network.

export interface ManifestOptions {
  title: string;
  description: string;
}

/** A short name for home screens (~12 characters fit under an icon). */
export function shortName(title: string): string {
  if (title.length <= 12) return title;
  const first = title.split(/[\s·:|-]+/)[0] ?? "";
  return first.length >= 3 && first.length <= 12 ? first : "Skills";
}

export function manifest(o: ManifestOptions): string {
  const m = {
    id: "./",
    name: o.title,
    short_name: shortName(o.title),
    description: o.description,
    lang: "en",
    start_url: "./",
    scope: "./",
    display: "standalone",
    background_color: "#f6f7f9",
    theme_color: "#ffffff",
    categories: ["developer", "productivity", "utilities"],
    icons: [
      { src: "assets/icons/icon.svg", sizes: "any", type: "image/svg+xml", purpose: "any" },
      { src: "assets/icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: "assets/icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      { src: "assets/icons/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
    shortcuts: [
      { name: "Plugins", url: "plugins/" },
      { name: "Tester", url: "tester/" },
    ],
  };
  return `${JSON.stringify(m, null, 2)}\n`;
}

/** The service worker script. `version` changes on every build, which makes browsers install the new worker. */
export function serviceWorker(version: string, precache: string[]): string {
  return `// Generated by skills-pages: offline support for this site. Build ${version}
const SCOPE = self.registration.scope;
const PREFIX = "skills-pages:" + SCOPE + ":";
const CACHE = PREFIX + ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE.map((u) => new URL(u, SCOPE).href)))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

async function networkFirst(request) {
  const cache = await caches.open(CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  } catch (err) {
    const navigate = request.mode === "navigate";
    const hit = await cache.match(request, { ignoreSearch: navigate });
    if (hit) return hit;
    if (navigate) {
      const home = await cache.match(new URL("./", SCOPE).href);
      if (home) return home;
    }
    throw err;
  }
}

async function cacheFirst(request) {
  const hit = await (await caches.open(CACHE)).match(request);
  return hit || networkFirst(request);
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || !request.url.startsWith(SCOPE)) return;
  const rel = request.url.slice(SCOPE.length).split(/[?#]/)[0];
  if (rel === "sw.js" || rel.startsWith(".well-known/") || /\\.zip$/i.test(rel)) return;
  event.respondWith(rel.startsWith("assets/") ? cacheFirst(request) : networkFirst(request));
});
`;
}

/** Width and height of a PNG, from its IHDR chunk. */
export function pngSize(png: Uint8Array): { width: number; height: number } | undefined {
  const sig = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  if (png.length < 24 || sig.some((b, i) => png[i] !== b)) return undefined;
  const v = new DataView(png.buffer, png.byteOffset, png.byteLength);
  return { width: v.getUint32(16), height: v.getUint32(20) };
}

/** favicon.ico holding one PNG image (supported by every current browser). */
export function ico(png: Uint8Array): Uint8Array {
  const size = pngSize(png);
  if (!size) throw new Error("favicon source is not a PNG");
  const out = new Uint8Array(22 + png.length);
  const v = new DataView(out.buffer);
  v.setUint16(2, 1, true); // type: icon
  v.setUint16(4, 1, true); // one image
  out[6] = size.width >= 256 ? 0 : size.width;
  out[7] = size.height >= 256 ? 0 : size.height;
  v.setUint16(10, 1, true); // colour planes
  v.setUint16(12, 32, true); // bits per pixel
  v.setUint32(14, png.length, true);
  v.setUint32(18, 22, true); // offset of the image data
  out.set(png, 22);
  return out;
}
